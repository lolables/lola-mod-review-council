  "verified": [], "correctable": [], "stripped": [],
  "total_findings": 0, "duplicates_consolidated": 0,
  "verdicts": {"divisor-guard-code": "REQUEST CHANGES"}
}
FJ
	[[ -n "$1" ]] && printf '%s' "$1" >"$s/verdict.txt"
	echo "$s"
}

